#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from the lockfiles: npm packages (pnpm) and Rust crates (cargo). Run: node scripts/notices.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const npm = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--json"], { encoding: "utf8", maxBuffer: 1 << 26 }));
const cargo = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1"], { encoding: "utf8", maxBuffer: 1 << 28 }));

const rows = [];
for (const [lic, pkgs] of Object.entries(npm)) for (const p of pkgs) for (const v of p.versions ?? [p.version]) rows.push(["npm", p.name, v, lic, p.homepage ?? ""]);
const members = new Set(cargo.workspace_members);
for (const p of cargo.packages) if (!members.has(p.id)) rows.push(["crate", p.name, p.version, p.license ?? "UNKNOWN", p.repository ?? ""]);
rows.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));

const flagged = rows.filter((r) => /(^|[^-])(A?GPL|SSPL)|UNKNOWN|UNLICENSED/i.test(r[3]) && !/OR (MIT|Apache)/i.test(r[3]));
const counts = {};
for (const r of rows) counts[r[3]] = (counts[r[3]] ?? 0) + 1;

const out = `# Third-party notices

Generated by \`node scripts/notices.mjs\` from the lockfiles on ${new Date().toISOString().slice(0, 10)}. ${rows.length} packages (npm and Rust crates). Each keeps its own licence; full texts are in the packages themselves.

## How this project was written
Most of the code in this repository was written by AI assistants (Anthropic Claude, in Claude Code sessions) working under the direction of the repository owner, who reviews and decides scope. Nothing was copied from other projects. Other projects (for example the Skarbnik entry, Walrus papers, NEAR AI's documentation) were read for ideas only.

## Notes
- Licence of this project: MIT OR Apache-2.0 (see LICENSE-MIT, LICENSE-APACHE). The owner must confirm before publishing: \`[NOT FINISHED]\`.
- Packages under MPL-2.0 are used unmodified as dependencies (file-level copyleft; no changes made).
- One Rust crate is offered as "MIT OR Apache-2.0 OR LGPL-2.1-or-later"; we use it under MIT.
- Copyleft or unknown licences that are not an alternative to MIT/Apache: ${flagged.length === 0 ? "none found" : flagged.map((r) => `${r[1]}@${r[2]} (${r[3]})`).join(", ")}.
- Pinned external value: the Intel SGX Root CA public key hash used by the attestation client (\`packages/ai/src/attest/tdx.ts\`), checked against Intel's published certificate.

## Licence counts
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`).join("\n")}

## Packages
| Kind | Name | Version | Licence |
|---|---|---|---|
${rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} | ${r[3].replace(/\|/g, "/")} |`).join("\n")}
`;
writeFileSync("THIRD_PARTY_NOTICES.md", out);
console.log(`wrote THIRD_PARTY_NOTICES.md: ${rows.length} packages; flagged: ${flagged.length}`);
