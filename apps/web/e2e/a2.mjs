import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const PDF = process.argv[2];
const browser = await launch();
const { page } = await newUser(browser);
await page.goto(APP);
await page.getByRole("button", { name: "Create with passkey" }).click();
await page.getByText("Your safes").waitFor({ timeout: 20000 });
await page.getByRole("button", { name: "New safe" }).click();
await page.getByText("Safe #1").waitFor({ timeout: 90000 });
await page.getByText("Safe #1").click();
await page.getByText("This safe is empty").waitFor({ timeout: 30000 });
const t0 = Date.now();
await page.locator('input[type=file]').setInputFiles({ name: "lease.pdf", mimeType: "application/pdf", buffer: readFileSync(PDF) });
await page.getByText("lease.pdf").first().waitFor({ timeout: 180000 });
console.log("pdf added in", Math.round((Date.now() - t0) / 1000), "s");
await page.locator('input[type=file]').setInputFiles({ name: "notes.txt", mimeType: "text/plain", buffer: Buffer.from("Deposit: 1,800. Keys at the agent.") });
await page.getByText("notes.txt").first().waitFor({ timeout: 180000 });
await page.getByText("Recorded on chain").waitFor();
console.log("both files listed; txs:", await page.locator("details tbody tr").count());
await page.locator(".card", { hasText: "lease.pdf" }).getByRole("button", { name: "Open" }).click();
await page.locator("img").first().waitFor({ timeout: 60000 });
const w = await page.locator("img").first().evaluate((i) => i.naturalWidth);
console.log("pdf page rendered, image width:", w);
await page.screenshot({ path: process.argv[3] ?? "a2.png" });
await browser.close();
