import { APP, launch, newUser } from "./lib.mjs";
const SHOT = process.argv[2];
const browser = await launch();
const owner = (await newUser(browser)).page;
await owner.setViewportSize({ width: 1440, height: 1000 });
await owner.goto(APP);
await owner.getByRole("button", { name: "Create with a passkey" }).click();
await owner.getByRole("heading", { name: "Your safes" }).waitFor({ timeout: 20000 });
await owner.getByRole("button", { name: "New safe" }).first().click(); await owner.getByRole("button", { name: "Create safe" }).click();
await owner.getByText("Safe 1", { exact: true }).first().waitFor({ timeout: 90000 });
await owner.getByText("Safe 1", { exact: true }).first().click();
await owner.getByText("This safe is empty").waitFor({ timeout: 30000 });
const inv = "INVOICE\nInvoice number: INV-2041\nIssue date: 3 November 2026\nDue date: 1 December 2026\nBill to: Ada Okoro\n| Item | Qty | Amount |\n|---|---|---|\n| Design work | 12 | £1,200.00 |\n| Total due | | £1,440.00 |\n";
await owner.locator('input[type=file]').setInputFiles({ name: "invoice.md", mimeType: "text/markdown", buffer: Buffer.from(inv) });
await owner.locator(".tray").waitFor({ state: "detached", timeout: 240000 });
await owner.getByRole("button", { name: "Claims", exact: true }).click();
await owner.getByText(/^Facts in invoice\.md/).waitFor({ timeout: 60000 });
console.log("facts:", JSON.stringify(await owner.locator(".facts .tr").evaluateAll((rs) => rs.map((r) => [...r.children].map((t) => t.textContent).slice(0, 2).join("=")))));
await owner.getByRole("button", { name: "Use Total due" }).click();
await owner.getByLabel("Condition").selectOption("<=");
await owner.getByLabel("Amount").fill("1500");
await owner.getByRole("button", { name: "Cross-check with a private model" }).click();
await owner.getByText(/The model read the same pages|could not be used/).waitFor({ timeout: 360000 });
console.log("cross:", await owner.locator(".cross-note").textContent(), JSON.stringify(await owner.locator(".xc").allTextContents()));
if (await owner.getByPlaceholder(/To self-declare/).count()) await owner.getByPlaceholder(/To self-declare/).fill("£1,440.00");
await owner.getByLabel("I checked this against the document myself").check();
await owner.getByRole("button", { name: "Sign claim" }).click();
await owner.getByText(/Grade [BC] claim saved/).waitFor({ timeout: 240000 });
console.log("claim:", await owner.getByText(/Grade [BC] claim saved/).textContent(), "|", (await owner.locator(".panel .tr span").allTextContents()).filter((t) => /Total due/.test(t)).join(" / "));
await owner.screenshot({ path: SHOT });
await browser.close();
