import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const [PAYSLIP, SHOT] = [process.argv[2], process.argv[3]];
const browser = await launch();
const owner = (await newUser(browser)).page;
await owner.goto(APP);
await owner.getByRole("button", { name: "Create with a passkey" }).click();
await owner.getByText("Your safes").waitFor({ timeout: 20000 });
await owner.getByRole("button", { name: "New safe" }).first().click(); await owner.getByRole("button", { name: "Create safe" }).click();
await owner.getByText("Safe 1", { exact: true }).first().waitFor({ timeout: 90000 });
await owner.getByText("Safe 1", { exact: true }).first().click();
await owner.getByText("This safe is empty").waitFor({ timeout: 30000 });
await owner.locator('input[type=file]').setInputFiles({ name: "payslip.pdf", mimeType: "application/pdf", buffer: readFileSync(PAYSLIP) });
await owner.getByText("payslip.pdf").first().waitFor({ timeout: 240000 });
await owner.getByRole("button", { name: "Claims", exact: true }).click();
await owner.locator("select").selectOption({ label: "payslip.pdf" });
await owner.getByText("Found on this device: payslip").waitFor({ timeout: 30000 });
console.log("rules found:", JSON.stringify(await owner.locator("table tbody tr").evaluateAll((rs) => rs.slice(0, 6).map((r) => [...r.querySelectorAll("td")].map((t) => t.textContent).slice(0, 2).join("="))).catch(() => []))); 
await owner.getByRole("button", { name: "Cross-check with a private model" }).click();
await owner.getByText(/The model read the same pages|could not be used/).waitFor({ timeout: 360000 }); console.log("cross-check text:", await owner.getByText(/The model read the same pages|could not be used/).textContent());
console.log("cross-check:", JSON.stringify(await owner.locator(".pill").allTextContents()));
if (/could not be used/.test(await owner.locator("p.note", { hasText: /model/ }).first().textContent().catch(() => ""))) { console.log("model unavailable: falling back to a self-declared claim (grade C)"); await owner.getByPlaceholder(/To self-declare/).fill("3,850.00"); }
await owner.getByLabel("I checked this against the document myself").check();
await owner.getByRole("button", { name: "Create signed claim" }).click();
await owner.getByText(/Grade [BC] claim saved|checked|Did not|no grade|rules and model/).first().waitFor({ timeout: 240000 }); console.log("after create:", (await owner.locator(".err").allTextContents()).join(" | ") || "no error", "|", (await owner.locator("table").first().innerText()).replace(/\s+/g," ").slice(0,300)); await owner.getByText(/Grade [BC] claim saved/).waitFor({ timeout: 240000 });
console.log("claim:", await owner.getByText(/Grade [BC] claim saved/).textContent());
await owner.getByRole("button", { name: "Give access" }).first().click();
await owner.getByLabel(/Claim: Monthly gross pay/).check();
await owner.getByPlaceholder("Who is this for?").fill("Landlord");
await owner.getByRole("button", { name: "Create link" }).click();
await owner.getByText("Link ready").waitFor({ timeout: 120000 });
const link = await owner.locator("input[readonly]").inputValue();
const rec = await (await browser.newContext({ viewport: { width: 1000, height: 1100 } })).newPage();
await rec.goto(link);
console.log("landlord sees files:", await rec.locator("li, strong").allTextContents().then((t) => t.filter((x) => /Claim|payslip/i.test(x))));
await rec.getByRole("button", { name: "Open" }).click();
await rec.getByText(/recorded · visit #1/).waitFor({ timeout: 120000 });
await rec.getByText(/Loading \d+ of/).waitFor({ state: "detached", timeout: 120000 });
console.log("landlord headings:", await rec.locator("h2").allTextContents());
await rec.screenshot({ path: SHOT });
await browser.close();
