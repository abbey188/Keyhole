import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const PDF = process.argv[2], SHOT = process.argv[3];
const browser = await launch();
const { page } = await newUser(browser);
page.on("console", (m) => { if (m.type() === "error") console.log("[console.error]", m.text().slice(0, 200)); });
await page.goto(APP);
await page.getByRole("button", { name: "Create with a passkey" }).click();
await page.getByText("Your safes").waitFor({ timeout: 20000 });
await page.getByRole("button", { name: "New safe" }).first().click(); await page.getByRole("button", { name: "Create safe" }).click();
await page.getByText("Safe 1", { exact: true }).first().waitFor({ timeout: 90000 });
await page.getByText("Safe 1", { exact: true }).first().click();
await page.getByText("This safe is empty").waitFor({ timeout: 30000 });
await page.locator('input[type=file]').setInputFiles({ name: "lease.pdf", mimeType: "application/pdf", buffer: readFileSync(PDF) });
await page.getByText("lease.pdf").first().waitFor({ timeout: 240000 });
console.log("notes shown:", await page.locator(".note", { hasText: "Text found" }).count() > 0);
await page.getByRole("button", { name: "Ask", exact: true }).click();
await page.getByText(/searchable pages in this safe/).waitFor({ timeout: 60000 });
console.log(await page.getByText(/searchable pages/).first().textContent());
await page.getByPlaceholder("e.g. How much is the monthly rent?").fill("How much is the monthly rent?");
const t0 = Date.now();
await page.getByRole("button", { name: "Ask", exact: true }).nth(1).click().catch(async () => { await page.keyboard.press("Enter"); });
await page.getByText("Private · attested hardware").waitFor({ timeout: 120000 });
console.log("answered in", Math.round((Date.now() - t0) / 1000), "s:", (await page.locator("p[style*='font-size']").first().textContent()));
console.log("citation:", (await page.locator("p.note", { hasText: "From " }).first().textContent()));
await page.getByText("Evidence").click();
console.log("evidence rows:", JSON.stringify(await page.locator("details tbody tr").evaluateAll((rs) => rs.map((r) => [...r.querySelectorAll("td")].map((t) => t.textContent.slice(0, 48)).join(": ")))));
// a question that is not in the safe: the model is never called
await page.getByPlaceholder("e.g. How much is the monthly rent?").fill("What is the airspeed velocity of a swallow?");
await page.keyboard.press("Enter");
await page.getByText("I can't find that in this safe.").waitFor({ timeout: 60000 });
console.log("unrelated question:", await page.getByText("Nothing left this device.").count() > 0 ? "answered locally, nothing sent" : "model was called");
await page.screenshot({ path: SHOT });
await browser.close();
