// Pop-up menus close on an outside tap, on Escape, and after choosing an option.
import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const browser = await launch();
const page = (await newUser(browser)).page;
const ok = (c, m) => { if (!c) { console.log("FAIL", m); process.exit(1); } console.log("ok", m); };
await page.goto(APP);
await page.getByRole("button", { name: "Create with a passkey" }).click();
await page.getByRole("heading", { name: "Your safes" }).waitFor({ timeout: 20000 });
await page.getByRole("button", { name: "New safe" }).first().click(); await page.getByRole("button", { name: "Create safe" }).click();
await page.getByText("Safe 1", { exact: true }).first().waitFor({ timeout: 90000 });
await page.getByText("Safe 1", { exact: true }).first().click();
await page.getByText("This safe is empty").waitFor({ timeout: 30000 });
await page.locator("input[type=file]").setInputFiles([{ name: "payslip.pdf", mimeType: "application/pdf", buffer: readFileSync(new URL("../../../demo/files/payslip-maria-santos.pdf", import.meta.url)) }]);
await page.locator(".tray").waitFor({ state: "detached", timeout: 240000 });
const actions = page.getByRole("button", { name: "File actions" });
const item = page.getByRole("button", { name: "Download" });
const outside = () => page.mouse.click(5, (page.viewportSize()?.height ?? 800) - 5);
await actions.click(); ok(await item.isVisible(), "file menu opens");
await outside(); ok(!(await item.isVisible()), "outside click closes it");
await actions.click(); await actions.click(); ok(!(await item.isVisible()), "the … button still toggles it closed");
await actions.click(); await page.keyboard.press("Escape"); ok(!(await item.isVisible()), "Escape closes it");
await actions.click(); await page.getByRole("button", { name: "Hide details…" }).click(); ok(!(await item.isVisible()), "choosing an option closes it");
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Claims", exact: true }).click();
await page.getByRole("button", { name: "Change file" }).click();
const pick = page.locator(".panel button.tr", { hasText: "payslip.pdf" });
ok(await pick.isVisible(), "Change file list opens");
await outside(); ok(!(await pick.isVisible()), "outside click closes the Change file list");
await browser.close();
