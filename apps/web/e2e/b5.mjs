// B5 on testnet: redact the passport's details, self-test, save the copy, share it; the recipient sees blocks, never the values.
import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const [PDF, SHOT] = [process.argv[2], process.argv[3]];
const browser = await launch();
const owner = (await newUser(browser)).page;
await owner.goto(APP);
await owner.getByRole("button", { name: "Create with passkey" }).click();
await owner.getByText("Your safes").waitFor({ timeout: 20000 });
await owner.getByRole("button", { name: "New safe" }).click();
await owner.getByText("Safe #1").waitFor({ timeout: 90000 });
await owner.getByText("Safe #1").click();
await owner.getByText("This safe is empty").waitFor({ timeout: 30000 });
await owner.locator("input[type=file]").setInputFiles({ name: "passport.pdf", mimeType: "application/pdf", buffer: readFileSync(PDF) });
await owner.getByText("passport.pdf").first().waitFor({ timeout: 240000 });
await owner.getByRole("button", { name: "Hide details…" }).click();
await owner.getByText("Self-test passed").waitFor({ timeout: 60000 });
console.log("detected:", JSON.stringify(await owner.locator("label.row").allTextContents()));
console.log("self-test:", await owner.getByText("Self-test passed").textContent(), "|", await owner.locator("p", { hasText: "hidden; no hidden value" }).first().textContent());
await owner.getByPlaceholder("Also hide this text").fill("SANTOS");
await owner.getByText("Self-test passed").waitFor();
await owner.getByRole("button", { name: "Save redacted copy" }).click();
await owner.getByText("passport (redacted).txt").first().waitFor({ timeout: 180000 });
console.log("owner: redacted copy saved");
await owner.getByRole("button", { name: "Access" }).click();
await owner.getByLabel("passport (redacted).txt").check();
await owner.getByPlaceholder("Who is this for?").fill("Landlord");
await owner.getByRole("button", { name: "Give access" }).click();
await owner.getByText("Link ready").waitFor({ timeout: 120000 });
const link = await owner.locator("input[readonly]").inputValue();
const rec = await (await browser.newContext({ viewport: { width: 1000, height: 900 } })).newPage();
await rec.goto(link);
await rec.getByRole("button", { name: "Open" }).click();
await rec.getByText(/recorded · visit #1/).waitFor({ timeout: 120000 });
await rec.getByText(/Loading \d+ of/).waitFor({ state: "detached", timeout: 120000 });
// the page is drawn on a canvas; read the text the viewer was given from the decrypted bytes via a test hook-free check: the DOM has no text
const dom = await rec.content();
console.log("values in the recipient's page source:", ["NV1234567", "1994-03-12", "SANTOS"].filter((v) => dom.includes(v)));
await rec.screenshot({ path: SHOT });
await browser.close();
