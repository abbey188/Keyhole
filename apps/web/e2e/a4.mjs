import { readFileSync } from "node:fs";
import { APP, launch, newUser } from "./lib.mjs";
const PDF = process.argv[2], SHOT = process.argv[3];
const browser = await launch();
const owner = (await newUser(browser)).page;
await owner.goto(APP);
await owner.getByRole("button", { name: "Create with a passkey" }).click();
await owner.getByText("Your safes").waitFor({ timeout: 20000 });
await owner.getByRole("button", { name: "New safe" }).first().click(); await owner.getByRole("button", { name: "Create safe" }).click();
await owner.getByText("Safe 1", { exact: true }).first().waitFor({ timeout: 90000 });
await owner.getByText("Safe 1", { exact: true }).first().click();
await owner.getByText("This safe is empty").waitFor({ timeout: 30000 });
await owner.locator('input[type=file]').setInputFiles({ name: "lease.pdf", mimeType: "application/pdf", buffer: readFileSync(PDF) });
await owner.getByText("lease.pdf").first().waitFor({ timeout: 180000 });
await owner.getByRole("button", { name: "Give access" }).first().click();
await owner.getByLabel("lease.pdf").check();
await owner.getByPlaceholder("Who is this for?").fill("Maria");
await owner.getByRole("button", { name: "Create link" }).click();
await owner.getByText("Link ready").waitFor({ timeout: 120000 });
const link = await owner.locator("input[readonly]").inputValue();
await owner.getByRole("button", { name: "Visitors" }).click();
await owner.getByText("No one has opened this safe yet").waitFor({ timeout: 30000 });
console.log("owner sees: no visitors yet");
const rec = await (await browser.newContext()).newPage();
await rec.goto(link);
await rec.getByRole("button", { name: "Open" }).click();
await rec.getByText(/recorded · visit #1/).waitFor({ timeout: 120000 });
const t0 = Date.now();
await owner.getByText(/Verified · 1 receipts/).waitFor({ timeout: 60000 });
console.log("owner: receipt appeared and verified", Math.round((Date.now() - t0) / 1000), "s after the recipient's open was shown");
await rec.getByText(/Loading \d+ of/).waitFor({ state: "detached", timeout: 120000 });
await rec.getByRole("button", { name: "I'm done" }).click();
await rec.getByText("This access has ended").waitFor({ timeout: 90000 });
await owner.getByText(/Verified · 3 receipts|Verified · 2 receipts/).waitFor({ timeout: 60000 });
console.log("owner rows:", JSON.stringify((await owner.locator("tbody tr").evaluateAll((rs) => rs.map((r) => [...r.querySelectorAll("td")].map((t) => t.textContent).join(" | "))))));
await owner.getByRole("button", { name: "Try a doctored copy" }).click();
await owner.getByText("Broken", { exact: true }).waitFor({ timeout: 30000 });
console.log("doctored copy:", (await owner.locator(".err").first().textContent()));
await owner.screenshot({ path: SHOT });
await browser.close();
