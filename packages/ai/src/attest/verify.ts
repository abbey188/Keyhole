/**
 * Client-side verification of a NEAR AI Cloud attestation report (GET /v1/attestation/report).
 * Every check is reported as passed / failed / not_performed. Nothing is "verified" by omission:
 * see NOT_CHECKED for what this module never does.
 */
import { secp256k1 } from "@noble/curves/secp256k1.js";
import { ed25519 } from "@noble/curves/ed25519.js";
import { keccak_256 } from "@noble/hashes/sha3.js";
import { sha256, sha384 } from "@noble/hashes/sha2.js";
import { bytesEqual, bytesToHex, concatBytes, hexToBytes, utf8 } from "../hex.js";
import { checkNvidiaPayload, type FetchLike } from "./nvidia.js";
import { parseTdxQuote, verifyQuoteSignatures, type TdxQuote } from "./tdx.js";

export type CheckStatus = "passed" | "failed" | "not_performed";
export interface AttestationCheck {
  /** "gateway" or "model[i]" */
  subject: string;
  name: string;
  status: CheckStatus;
  detail: string;
}

/** What a caller can inject to cover Intel collateral (TCB status, CRLs, QE identity). */
export type CollateralVerifier = (quote: Uint8Array) => Promise<{ status: string; accepted: boolean; detail?: string }>;

export interface AttestOptions {
  /** 64 hex chars (32 bytes) generated by the client for this request */
  nonce: string;
  expectedModel: string;
  /** ms since epoch, for certificate validity. Default Date.now() */
  now?: number;
  /** Used for NVIDIA NRAS. Default: globalThis.fetch */
  fetch?: FetchLike;
  /** Call NVIDIA NRAS for GPU evidence (default true). false -> check reported not_performed */
  nras?: boolean;
  /** Intel PCS / PCCS based verification (TCB status). If absent the tcb_status check is not_performed */
  collateralVerifier?: CollateralVerifier;
  pinnedRootSpkiSha256?: string;
  /** Require a "gateway_attestation" with its own checks (default true) */
  checkGateway?: boolean;
}

export interface AttestationResult {
  /** No check failed, a matching model candidate exists, and every REQUIRED_CHECKS entry passed for it */
  ok: boolean;
  /** ok AND no check is not_performed (needs collateralVerifier and NRAS) */
  complete: boolean;
  model: string;
  signing_algo?: string;
  signing_address?: string;
  /** model public key from the verified candidate (the key E2EE encrypts to) */
  signing_public_key?: string;
  /** sha256 hex of the canonical JSON of the selected model candidate */
  report_hash?: string;
  measurements?: { mr_td: string; rtmr0: string; rtmr1: string; rtmr2: string; rtmr3: string; mr_config_id: string; compose_hash: string };
  checks: AttestationCheck[];
  not_checked: string[];
}

/** Checks that must be "passed" on the selected model candidate (and on the gateway) for ok=true. */
export const REQUIRED_CHECKS = [
  "nonce_echo",
  "signing_key_binding",
  "quote_structure",
  "quote_signature",
  "qe_report_binding",
  "qe_report_signature",
  "pck_chain",
  "pck_root_pinned",
  "report_data_binds_signer_and_nonce",
  "td_debug_off",
  "mr_config_id_matches_app_compose",
  "event_log_replays_to_rtmr3",
] as const;

export const NOT_CHECKED: readonly string[] = [
  "Intel TCB status, advisories, CRLs and QE identity (needs Intel PCS collateral) unless a collateralVerifier is supplied",
  "Whether the measured workload (MRTD, RTMRs, compose hash, OS image hash) is one you accept: no allowlist or image provenance is applied; measurements are returned for a policy to judge",
  "Which model the enclave actually serves: the quote does not contain the model name; model_name is an unauthenticated label",
  "That the GPU evidence belongs to the same VM as the TDX quote (they share only the client nonce)",
  "NVIDIA JWKS certificate chain to an NVIDIA root (JWKS is trusted over TLS) and per-GPU claim policy",
  "ohttp_attestation / compose_manager_attestation / TLS certificate binding of the gateway connection",
  "That instances behind the same signing key are the same as the one that served a request",
];

type Obj = Record<string, unknown>;
const asObj = (v: unknown): Obj => (typeof v === "string" ? (JSON.parse(v) as Obj) : (v as Obj));

export function canonicalJson(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(canonicalJson).join(",")}]`;
  if (v && typeof v === "object") {
    const o = v as Obj;
    return `{${Object.keys(o)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonicalJson(o[k])}`)
      .join(",")}}`;
  }
  return JSON.stringify(v);
}
export const reportHash = (candidate: unknown): string => bytesToHex(sha256(utf8(canonicalJson(candidate))));

/** RTMR3 replay as in NEAR AI's docs: only imr==3 events, digest = SHA-384(type_le || ":" || event || ":" || payload). */
export function replayRtmr3(eventLog: unknown): Uint8Array {
  const events = asObj(eventLog) as unknown as { imr: number; event_type: number; event?: string; event_payload?: string; digest?: string }[];
  if (!Array.isArray(events)) throw new Error("event_log is not a list");
  let rtmr = new Uint8Array(48);
  for (const e of events) {
    if (e.imr !== 3) continue;
    const t = new Uint8Array(4);
    new DataView(t.buffer).setUint32(0, e.event_type, true);
    const digest = sha384(concatBytes(t, utf8(":"), utf8(e.event ?? ""), utf8(":"), hexToBytes(e.event_payload ?? "", "event_payload")));
    if (e.digest && !bytesEqual(hexToBytes(e.digest, "event digest"), digest)) throw new Error(`event digest mismatch for ${e.event}`);
    rtmr = sha384(concatBytes(rtmr, digest));
  }
  return rtmr;
}

/** Ethereum-style address (20 bytes) of an uncompressed secp256k1 public key given as 64 bytes X||Y. */
export function ethAddressOf(xy: Uint8Array): Uint8Array {
  return keccak_256(xy).subarray(12);
}

function signerIdentity(r: Obj): { algo: string; identity: Uint8Array; publicKey?: Uint8Array } {
  const algo = r.signing_algo;
  const identity = hexToBytes(String(r.signing_address), "signing_address");
  if (algo === "ed25519") {
    if (identity.length !== 32) throw new Error("ed25519 identity must be 32 bytes");
    return { algo, identity };
  }
  if (algo === "ecdsa") {
    if (identity.length !== 20) throw new Error("ecdsa identity must be 20 bytes");
    return { algo, identity };
  }
  throw new Error(`unsupported signing_algo ${String(algo)}`);
}

async function checkSubject(subject: string, r: Obj, isModel: boolean, o: Required<Pick<AttestOptions, "nonce">> & AttestOptions, now: number): Promise<{ checks: AttestationCheck[]; quote?: TdxQuote }> {
  const checks: AttestationCheck[] = [];
  const add = (name: string, status: CheckStatus, detail: string) => checks.push({ subject, name, status, detail });
  const run = (name: string, f: () => string) => {
    try {
      add(name, "passed", f());
    } catch (e) {
      add(name, "failed", (e as Error).message);
    }
  };
  const nonce = hexToBytes(o.nonce, "nonce");
  if (nonce.length !== 32) throw new Error("nonce must be 32 bytes (64 hex)");

  run("nonce_echo", () => {
    if (typeof r.request_nonce !== "string" || r.request_nonce.toLowerCase() !== o.nonce.toLowerCase()) throw new Error("request_nonce does not equal the client nonce");
    return "report echoes the client nonce";
  });

  let id: ReturnType<typeof signerIdentity> | undefined;
  run("signing_key_binding", () => {
    id = signerIdentity(r);
    if (id.algo === "ed25519") {
      if (isModel) {
        const pk = hexToBytes(String(r.signing_public_key), "signing_public_key");
        if (!bytesEqual(pk, id.identity)) throw new Error("signing_address is not the signing_public_key");
      }
      ed25519.Point.fromBytes(id.identity); // must be a valid curve point
      return "signing_address is a valid Ed25519 public key" + (isModel ? " equal to signing_public_key" : "");
    }
    if (!isModel) return "gateway ECDSA address (no public key in report to derive from)";
    let pk = hexToBytes(String(r.signing_public_key), "signing_public_key");
    if (pk.length === 65 && pk[0] === 4) pk = pk.subarray(1);
    if (pk.length !== 64) throw new Error("ecdsa signing_public_key must be 64 bytes (X||Y)");
    secp256k1.Point.fromBytes(concatBytes(new Uint8Array([4]), pk)); // on-curve check
    if (!bytesEqual(ethAddressOf(pk), id.identity)) throw new Error("signing_address is not keccak256(public key)[12:]");
    return "signing_address = keccak256(public key)[12:], key on secp256k1";
  });

  let quote: TdxQuote | undefined;
  let quoteBytes: Uint8Array | undefined;
  try {
    quoteBytes = hexToBytes(String(r.intel_quote), "intel_quote");
    quote = parseTdxQuote(quoteBytes);
    add("quote_structure", "passed", "TDX quote v4, ECDSA-P256 attestation key, parsed");
  } catch (e) {
    add("quote_structure", "failed", (e as Error).message);
  }

  if (quote) {
    for (const c of verifyQuoteSignatures(quote, { now, pinnedRootSpkiSha256: o.pinnedRootSpkiSha256 })) add(c.name, c.ok ? "passed" : "failed", c.detail);
    run("report_data_binds_signer_and_nonce", () => {
      if (!id) throw new Error("signing identity unusable");
      const want = concatBytes(concatBytes(id.identity, new Uint8Array(32 - id.identity.length)), nonce);
      if (!bytesEqual((quote as TdxQuote).reportData, want)) throw new Error("quote report_data != signer(32, zero-padded) || nonce");
      if (typeof r.report_data === "string" && r.report_data.toLowerCase() !== bytesToHex((quote as TdxQuote).reportData)) throw new Error("report_data field differs from the quote");
      return "quote report_data = signing identity || client nonce (taken from the signed quote, not the JSON field)";
    });
    run("td_debug_off", () => {
      if (((quote as TdxQuote).tdAttributes[0] as number) & 1) throw new Error("TDX debug attribute is set");
      return "TD_ATTRIBUTES debug bit is clear";
    });
    run("mr_config_id_matches_app_compose", () => {
      const tcb = asObj(asObj(r.info).tcb_info);
      if (typeof tcb.app_compose !== "string") throw new Error("no app_compose");
      const want = concatBytes(new Uint8Array([1]), sha256(utf8(tcb.app_compose)), new Uint8Array(15));
      if (!bytesEqual((quote as TdxQuote).mrConfigId, want)) throw new Error("MRCONFIGID != 01 || sha256(app_compose) || 0^15");
      return "MRCONFIGID binds the exact app_compose bytes";
    });
    run("event_log_replays_to_rtmr3", () => {
      const got = replayRtmr3(r.event_log);
      if (!bytesEqual(got, (quote as TdxQuote).rtmr[3])) throw new Error("replayed RTMR3 != quote RTMR3");
      return "RTMR3 replay of the imr=3 events equals the quote's RTMR3";
    });
  } else {
    for (const n of ["report_data_binds_signer_and_nonce", "td_debug_off", "mr_config_id_matches_app_compose", "event_log_replays_to_rtmr3", "qe_report_binding", "qe_report_signature", "pck_chain", "pck_root_pinned", "quote_signature"]) add(n, "failed", "no parseable quote");
  }

  if (o.collateralVerifier && quoteBytes) {
    try {
      const v = await o.collateralVerifier(quoteBytes);
      add("tcb_status", v.accepted ? "passed" : "failed", `${v.status}${v.detail ? `: ${v.detail}` : ""}`);
    } catch (e) {
      add("tcb_status", "failed", `collateral verifier error: ${(e as Error).message}`);
    }
  } else {
    add("tcb_status", "not_performed", "no Intel collateral verifier supplied: TCB level, advisories, CRLs and QE identity are unchecked");
  }

  if (isModel) {
    if (typeof r.nvidia_payload === "string" && r.nvidia_payload) {
      let nonceOk = false;
      try {
        nonceOk = String((JSON.parse(r.nvidia_payload) as Obj).nonce).toLowerCase() === o.nonce.toLowerCase();
      } catch {
        /* handled below */
      }
      add("nvidia_payload_nonce", nonceOk ? "passed" : "failed", nonceOk ? "GPU evidence nonce equals the client nonce" : "GPU evidence nonce differs from the client nonce or payload is not JSON");
      const f = o.fetch ?? (globalThis.fetch as unknown as FetchLike | undefined);
      if (o.nras === false || !f) add("nvidia_nras", "not_performed", o.nras === false ? "NRAS call disabled by caller" : "no fetch available");
      else if (!nonceOk) add("nvidia_nras", "failed", "not sent: nonce mismatch");
      else {
        const n = await checkNvidiaPayload(r.nvidia_payload, o.nonce, f, now);
        add("nvidia_nras", n.ok ? "passed" : "failed", n.detail);
      }
    } else {
      add("nvidia_payload_nonce", "not_performed", "no nvidia_payload in the report");
      add("nvidia_nras", "not_performed", "no nvidia_payload in the report");
    }
  }
  return { checks, quote };
}

export async function verifyAttestation(report: unknown, opts: AttestOptions): Promise<AttestationResult> {
  const now = opts.now ?? Date.now();
  const checks: AttestationCheck[] = [];
  const res: AttestationResult = { ok: false, complete: false, model: opts.expectedModel, checks, not_checked: [...NOT_CHECKED] };
  const fail = (subject: string, name: string, detail: string) => checks.push({ subject, name, status: "failed", detail });
  const o = { ...opts, nonce: opts.nonce.toLowerCase() };
  try {
    if (!/^[0-9a-f]{64}$/.test(o.nonce)) throw new Error("nonce must be 64 hex chars");
  } catch (e) {
    fail("report", "nonce_format", (e as Error).message);
    return res;
  }
  const rep = report as Obj | null;
  if (!rep || typeof rep !== "object") {
    fail("report", "report_shape", "report is not an object");
    return res;
  }

  if (opts.checkGateway !== false) {
    if (!rep.gateway_attestation) fail("gateway", "present", "gateway_attestation missing");
    else {
      try {
        checks.push(...(await checkSubject("gateway", rep.gateway_attestation as Obj, false, o, now)).checks);
      } catch (e) {
        fail("gateway", "verify", (e as Error).message);
      }
    }
  }

  const cands = Array.isArray(rep.model_attestations) ? (rep.model_attestations as Obj[]) : [];
  if (cands.length === 0) fail("model", "present", "model_attestations missing or empty");
  const matching: number[] = [];
  const perCand: { i: number; checks: AttestationCheck[]; quote?: TdxQuote }[] = [];
  for (let i = 0; i < cands.length; i++) {
    const c = cands[i] as Obj;
    const subject = `model[${i}]`;
    if (c.model_name !== opts.expectedModel) {
      checks.push({ subject, name: "model_name_label_matches", status: "failed", detail: `model_name "${String(c.model_name)}" != expected "${opts.expectedModel}"` });
      continue;
    }
    matching.push(i);
    try {
      const r = await checkSubject(subject, c, true, o, now);
      perCand.push({ i, ...r });
      checks.push({ subject, name: "model_name_label_matches", status: "passed", detail: "model_name equals the expected id (an unauthenticated label: the quote does not contain the model name)" }, ...r.checks);
    } catch (e) {
      fail(subject, "verify", (e as Error).message);
    }
  }
  if (cands.length > 0 && matching.length === 0) fail("model", "expected_model_present", `no candidate for ${opts.expectedModel}`);

  // all candidates of the expected model must be fine; pick the first as the reported key
  const anyFailed = checks.some((c) => c.status === "failed");
  const sel = perCand[0];
  if (sel) {
    const c = cands[sel.i] as Obj;
    res.signing_algo = String(c.signing_algo);
    res.signing_address = String(c.signing_address);
    res.signing_public_key = String(c.signing_public_key);
    res.report_hash = reportHash(c);
    if (sel.quote) {
      const q = sel.quote;
      res.measurements = {
        mr_td: bytesToHex(q.mrTd),
        rtmr0: bytesToHex(q.rtmr[0]),
        rtmr1: bytesToHex(q.rtmr[1]),
        rtmr2: bytesToHex(q.rtmr[2]),
        rtmr3: bytesToHex(q.rtmr[3]),
        mr_config_id: bytesToHex(q.mrConfigId),
        compose_hash: bytesToHex(q.mrConfigId.subarray(1, 33)),
      };
    }
  }
  const requiredSubjects = [...(opts.checkGateway !== false ? ["gateway"] : []), ...(sel ? [`model[${sel.i}]`] : [])];
  const requiredOk =
    !!sel &&
    requiredSubjects.every((s) => REQUIRED_CHECKS.every((n) => checks.some((c) => c.subject === s && c.name === n && c.status === "passed")));
  res.ok = !anyFailed && requiredOk;
  res.complete = res.ok && !checks.some((c) => c.status === "not_performed");
  return res;
}

export interface FetchReportOptions {
  baseUrl?: string;
  fetch?: FetchLike;
  apiKey?: string;
  signingAlgo?: "ed25519" | "ecdsa";
}

/** GET /v1/attestation/report for a canonical model id with provider=near and no aliasing. */
export async function fetchAttestationReport(model: string, nonce: string, o: FetchReportOptions = {}): Promise<unknown> {
  const f = o.fetch ?? (globalThis.fetch as unknown as FetchLike);
  const q = new URLSearchParams({ model, provider: "near", signing_algo: o.signingAlgo ?? "ed25519", include_tls_fingerprint: "false", nonce });
  const headers: Record<string, string> = { Accept: "application/json", "x-no-aliasing": "true" };
  if (o.apiKey) headers.Authorization = `Bearer ${o.apiKey}`;
  const res = await f(`${o.baseUrl ?? "https://cloud-api.near.ai"}/v1/attestation/report?${q}`, { headers });
  if (!res.ok) throw new Error(`attestation report request failed: HTTP ${res.status}`);
  return res.json();
}
